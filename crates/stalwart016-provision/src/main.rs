//! stalwart016-provision — recovery-mode provisioner for Stalwart Mail Server 0.16.
//!
//! Replaces the `writeShellApplication` shell script in the `stalwart016` NixOS
//! module with a robust Rust binary.  The lifecycle is:
//!
//! 1. Read a JSON config file (generated at Nix eval time) for all static settings.
//! 2. Check marker files to decide whether migration and/or registry plans need
//!    applying.  If nothing is pending, exit 0.
//! 3. Optionally probe the PostgreSQL store to guard against a silently-recreated DB.
//! 4. Start stalwart in recovery mode, wait for readiness, apply plans, write
//!    markers, query objects for evidence, and exit (killing the recovery process).

mod apply;
mod error;
mod health;
mod markers;
mod recovery;

use std::fmt;
use std::fs;
use std::net::TcpStream;
use std::path::PathBuf;
use std::time::Duration;

use anyhow::{Context, Result, bail};
use chrono::Utc;
use clap::Parser;
use serde::Deserialize;

/// CLI entrypoint for the stalwart016 provisioner.
///
/// Static settings (paths, hostname, timeouts) come from a JSON config file
/// generated at Nix eval time.  Runtime-only paths — the credentials inside
/// systemd's `$CREDENTIALS_DIRECTORY` — are passed as separate CLI args so
/// their store-path-free runtime resolution is preserved.
#[derive(Parser, Debug)]
#[command(
    name = "stalwart016-provision",
    about = "Stalwart 0.16 recovery-mode provisioner",
    version
)]
struct Cli {
    /// Path to the JSON config file generated by the Nix module.
    #[arg(long)]
    config: PathBuf,

    /// Path to the recovery admin password file inside systemd's credentials
    /// directory (e.g. `%d/recovery_admin_password`).
    #[arg(long)]
    recovery_password_file: PathBuf,

    /// Path to the PG password file inside systemd's credentials directory
    /// (only needed when store health check is enabled).
    #[arg(long)]
    pg_password_file: Option<PathBuf>,
}

/// Static settings generated by the Nix module at eval time.
#[derive(Debug, Deserialize)]
struct Config {
    #[serde(rename = "migration_marker_file")]
    migration_marker: PathBuf,
    #[serde(rename = "registry_marker_file")]
    registry_marker: PathBuf,
    #[serde(rename = "legacy_marker_file")]
    legacy_marker: PathBuf,
    #[serde(rename = "generated_plan_file")]
    plan: PathBuf,

    #[serde(default)]
    migration_apply_files: Vec<PathBuf>,

    #[serde(rename = "stalwart_binary")]
    stalwart_bin: PathBuf,
    #[serde(rename = "stalwart_config")]
    stalwart_cfg: PathBuf,
    hostname: String,
    #[serde(rename = "stalwart_cli_binary")]
    cli_bin: PathBuf,

    #[serde(default = "default_recovery_url")]
    recovery_url: String,
    #[serde(default = "default_admin_username")]
    recovery_admin_username: String,

    #[serde(default = "default_startup_attempts")]
    startup_attempts: u32,
    #[serde(
        default = "default_startup_interval",
        deserialize_with = "deserialize_f64"
    )]
    startup_interval_secs: f64,

    #[serde(default = "default_query_output_dir")]
    query_output_dir: PathBuf,
    #[serde(default = "default_query_objects")]
    query_objects: Vec<String>,

    #[serde(default)]
    continue_on_error: bool,

    #[serde(default)]
    require_verified_backup_sentinel: Option<PathBuf>,

    #[serde(default)]
    store_health_check: bool,
    #[serde(default = "default_probe_table")]
    probe_table: String,

    #[serde(default)]
    psql_binary: Option<PathBuf>,
    #[serde(default = "default_pg_host")]
    pg_host: String,
    #[serde(default = "default_pg_port")]
    pg_port: u16,
    #[serde(default = "default_pg_user")]
    pg_user: String,
    #[serde(default = "default_pg_database")]
    pg_database: String,
}

/// Deserialize an f64 from either a JSON number or a string.
fn deserialize_f64<'de, D: serde::Deserializer<'de>>(d: D) -> Result<f64, D::Error> {
    use serde::de;
    struct F64OrString;
    impl<'de> de::Visitor<'de> for F64OrString {
        type Value = f64;
        fn expecting(&self, f: &mut fmt::Formatter) -> fmt::Result {
            f.write_str("a float or a string containing a float")
        }
        fn visit_f64<E: de::Error>(self, v: f64) -> Result<f64, E> {
            Ok(v)
        }
        fn visit_u64<E: de::Error>(self, v: u64) -> Result<f64, E> {
            Ok(v as f64)
        }
        fn visit_i64<E: de::Error>(self, v: i64) -> Result<f64, E> {
            Ok(v as f64)
        }
        fn visit_str<E: de::Error>(self, v: &str) -> Result<f64, E> {
            v.parse().map_err(de::Error::custom)
        }
    }
    d.deserialize_any(F64OrString)
}

